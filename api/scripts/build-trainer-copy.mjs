#!/usr/bin/env node
// Writes api/trainers/push-copy.js, the server's copy of what a member is told when a trainer or
// gym does something (push and in-app notice), from frontend/src/lib/trainer-notices.js and its
// translations in frontend/src/locales. Same idea as build-nudge-copy.mjs; test/trainer-copy.test.js
// fails when the two drift.
//
//   node scripts/build-trainer-copy.mjs          # rewrite trainers/push-copy.js
//   node scripts/build-trainer-copy.mjs --check  # exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const API = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FRONT = path.join(API, '..', 'frontend', 'src');
const OUT = path.join(API, 'trainers', 'push-copy.js');

export async function buildTrainerCopy() {
  const { TRAINER_PUSH } = await import(pathToFileURL(path.join(FRONT, 'lib', 'trainer-notices.js')));
  const langs = fs.readdirSync(path.join(FRONT, 'locales')).filter(f => /^[a-zA-Z-]+\.js$/.test(f)).map(f => f.slice(0, -3)).sort();
  const copy = { en: TRAINER_PUSH };
  for (const lang of langs) {
    const pack = (await import(pathToFileURL(path.join(FRONT, 'locales', lang + '.js')))).default;
    const tr = s => (s ? pack[s] || s : s);
    copy[lang] = Object.fromEntries(Object.entries(TRAINER_PUSH).map(([k, c]) => [k, { title: tr(c.title), body: tr(c.body) }]));
  }
  return '// GENERATED by scripts/build-trainer-copy.mjs from frontend/src/lib/trainer-notices.js and frontend/src/locales.\n'
    + '// Do not edit by hand: change the frontend strings and run the script again.\n'
    + 'export const TRAINER_COPY = ' + JSON.stringify(copy, null, 2) + ';\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await buildTrainerCopy();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('api/trainers/push-copy.js is out of date: run node scripts/build-trainer-copy.mjs'); process.exit(1); }
    console.log('api/trainers/push-copy.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote', path.relative(process.cwd(), OUT));
  }
}
