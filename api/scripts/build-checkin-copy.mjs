#!/usr/bin/env node
// Writes api/checkin-copy.js, the server's copy of the check-in reminder's web push, from the source
// of truth in the frontend: the English words in frontend/src/lib/checkin-reminder.js (CHECKIN_PUSH)
// and their translations in frontend/src/locales, the way build-wrapped-copy.mjs does it for the
// December push. test/checkin-reminder.test.js fails when the two have drifted.
//
//   node scripts/build-checkin-copy.mjs          # rewrite checkin-copy.js
//   node scripts/build-checkin-copy.mjs --check  # exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const API = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FRONT = path.join(API, '..', 'frontend', 'src');
const OUT = path.join(API, 'checkin-copy.js');

export async function buildCheckinCopy() {
  const { CHECKIN_PUSH } = await import(pathToFileURL(path.join(FRONT, 'lib', 'checkin-reminder.js')));
  const langs = fs.readdirSync(path.join(FRONT, 'locales')).filter(f => /^[a-zA-Z-]+\.js$/.test(f)).map(f => f.slice(0, -3)).sort();
  const copy = { en: CHECKIN_PUSH };
  for (const lang of langs) {
    const pack = (await import(pathToFileURL(path.join(FRONT, 'locales', lang + '.js')))).default;
    copy[lang] = Object.fromEntries(Object.entries(CHECKIN_PUSH).map(([k, v]) => [k, pack[v] || v]));
  }
  return '// GENERATED by scripts/build-checkin-copy.mjs from frontend/src/lib/checkin-reminder.js and frontend/src/locales.\n'
    + '// Do not edit by hand: change the frontend strings and run the script again.\n'
    + 'export const CHECKIN_COPY = ' + JSON.stringify(copy, null, 2) + ';\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await buildCheckinCopy();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('api/checkin-copy.js is out of date: run node scripts/build-checkin-copy.mjs'); process.exit(1); }
    console.log('api/checkin-copy.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote', path.relative(process.cwd(), OUT));
  }
}
