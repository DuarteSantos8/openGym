#!/usr/bin/env node
// Writes api/nudge-copy.js — the server's copy of the missed-workout nudge text — from the source
// of truth in the frontend: the English pool in frontend/src/lib/nudge.js and its translations in
// frontend/src/locales. The api image carries no frontend, so the text has to live here too;
// this keeps the two from drifting (test/nudge-copy.test.js fails when they have).
//
//   node scripts/build-nudge-copy.mjs          # rewrite nudge-copy.js
//   node scripts/build-nudge-copy.mjs --check  # exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const API = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FRONT = path.join(API, '..', 'frontend', 'src');
const OUT = path.join(API, 'nudge-copy.js');

export async function buildNudgeCopy() {
  const { NUDGE_COPY } = await import(pathToFileURL(path.join(FRONT, 'lib', 'nudge.js')));
  const langs = fs.readdirSync(path.join(FRONT, 'locales')).filter(f => /^[a-zA-Z-]+\.js$/.test(f)).map(f => f.slice(0, -3)).sort();
  const copy = { en: NUDGE_COPY };
  for (const lang of langs) {
    const pack = (await import(pathToFileURL(path.join(FRONT, 'locales', lang + '.js')))).default;
    const tr = s => pack[s] || s;
    copy[lang] = Object.fromEntries(Object.entries(NUDGE_COPY).map(([tone, c]) => [tone, { title: tr(c.title), lines: c.lines.map(tr) }]));
  }
  return '// GENERATED by scripts/build-nudge-copy.mjs from frontend/src/lib/nudge.js and frontend/src/locales.\n'
    + '// Do not edit by hand: change the frontend strings and run the script again.\n'
    + 'export const NUDGE_COPY = ' + JSON.stringify(copy, null, 2) + ';\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await buildNudgeCopy();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('api/nudge-copy.js is out of date: run node scripts/build-nudge-copy.mjs'); process.exit(1); }
    console.log('api/nudge-copy.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote', path.relative(process.cwd(), OUT));
  }
}
