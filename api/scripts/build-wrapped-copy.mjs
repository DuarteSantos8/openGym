#!/usr/bin/env node
// Writes api/wrapped-copy.js — the server's copy of the December "Your year in openGym" push — from
// the source of truth in the frontend: the English words in frontend/src/lib/wrapped-copy.js and
// their translations in frontend/src/locales. The api image carries no frontend, so the text has to
// live here too, the way the nudge's does (build-nudge-copy.mjs); test/wrapped.test.js fails when
// the two have drifted.
//
//   node scripts/build-wrapped-copy.mjs          # rewrite wrapped-copy.js
//   node scripts/build-wrapped-copy.mjs --check  # exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const API = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FRONT = path.join(API, '..', 'frontend', 'src');
const OUT = path.join(API, 'wrapped-copy.js');

export async function buildWrappedCopy() {
  const { WRAPPED_PUSH } = await import(pathToFileURL(path.join(FRONT, 'lib', 'wrapped-copy.js')));
  const langs = fs.readdirSync(path.join(FRONT, 'locales')).filter(f => /^[a-zA-Z-]+\.js$/.test(f)).map(f => f.slice(0, -3)).sort();
  const copy = { en: WRAPPED_PUSH };
  for (const lang of langs) {
    const pack = (await import(pathToFileURL(path.join(FRONT, 'locales', lang + '.js')))).default;
    copy[lang] = { title: pack[WRAPPED_PUSH.title] || WRAPPED_PUSH.title, body: pack[WRAPPED_PUSH.body] || WRAPPED_PUSH.body };
  }
  return '// GENERATED by scripts/build-wrapped-copy.mjs from frontend/src/lib/wrapped-copy.js and frontend/src/locales.\n'
    + '// Do not edit by hand: change the frontend strings and run the script again.\n'
    + 'export const WRAPPED_COPY = ' + JSON.stringify(copy, null, 2) + ';\n';
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = await buildWrappedCopy();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('api/wrapped-copy.js is out of date: run node scripts/build-wrapped-copy.mjs'); process.exit(1); }
    console.log('api/wrapped-copy.js is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote', path.relative(process.cwd(), OUT));
  }
}
