#!/usr/bin/env node
// The API Docker context cannot import frontend/. Bundle the canonical pure helper,
// just as build-coach-assets generates the server's catalogue. No new dependency.
import { rolldown } from '../frontend/node_modules/rolldown/dist/index.mjs'
import { readFileSync, writeFileSync } from 'node:fs'
const root = new URL('../', import.meta.url)
const bundle = await rolldown({
  input: new URL('frontend/src/lib/routine-mutations.js', root).pathname,
  // The server needs catalogue identity/equipment, not GIFs or instruction text.
  // build-coach-assets already checks this slim index against the same dataset.
  plugins: [{
    name: 'server-catalogue',
    resolveId(source) { if (source === './exercises-data.js') return '\0server-catalogue' },
    load(id) {
      if (id === '\0server-catalogue') return 'export { EXERCISES as EXDB } from ' + JSON.stringify(new URL('api/coach/core/library-data.js', root).pathname)
    }
  }]
})
const result = await bundle.generate({ format: 'esm', minify: true })
await bundle.close()
const body = '// GENERATED by scripts/build-routine-assets.mjs; edit frontend/src/lib/routine-mutations.js and its dependencies.\n' + result.output[0].code
const file = new URL('api/routine-mutations.js', root)
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== body) throw new Error('Routine assets stale; run node scripts/build-routine-assets.mjs')
} else writeFileSync(file, body)
