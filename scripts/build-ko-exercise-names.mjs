#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
const args = process.argv.slice(2)
const option = key => { const i = args.indexOf(key); return i < 0 ? null : args[i + 1] }
const root = resolve(option('--root') || resolve(dirname(fileURLToPath(import.meta.url)), '..'))
const sourcePath = resolve(option('--source') || resolve(root, 'scripts/exercise-name-sources/ko.json'))
const raw = readFileSync(sourcePath, 'utf8')
const source = JSON.parse(raw)
if (!source || Array.isArray(source) || typeof source !== 'object') throw new Error('Expected ID → name object')
// JSON.parse otherwise silently accepts a duplicate key and discards its first value.
const seen = new Set()
for (const match of raw.matchAll(/"((?:\\.|[^"\\])*)"\s*:/g)) {
  const id = JSON.parse(`"${match[1]}"`)
  if (seen.has(id)) throw new Error(`Duplicate exercise ID: ${id}`)
  seen.add(id)
}
const { EXDB } = await import(pathToFileURL(resolve(root, 'frontend/src/lib/exercises-data.js')))
const known = new Set(EXDB.map(e => e.id))
if (known.size !== EXDB.length) throw new Error('Duplicate built-in catalogue ID')
for (const [id, name] of Object.entries(source)) {
  if (!known.has(id)) throw new Error(`Unknown exercise ID: ${id}`)
  if (typeof name !== 'string' || !name.trim()) throw new Error(`${id}: name must be a non-empty string`)
  if (name !== name.trim()) throw new Error(`${id}: remove surrounding whitespace`)
}
if (Object.keys(source).length !== EXDB.length) throw new Error(`Incomplete ko exercise names: ${Object.keys(source).length}/${EXDB.length}`)
const ordered = Object.fromEntries(EXDB.map(e => [e.id, source[e.id]]))
const outputPath = resolve(root, 'frontend/src/exercise-names/ko.js')
mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, '// generated by scripts/build-ko-exercise-names.mjs — edit scripts/exercise-name-sources/ko.json\nexport default ' + JSON.stringify(ordered) + '\n')
console.log(`Generated ${EXDB.length}/${EXDB.length} ko exercise names; unique IDs, exact catalogue, non-empty values validated.`)
