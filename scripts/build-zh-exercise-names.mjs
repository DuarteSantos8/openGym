#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const { EXDB } = await import(pathToFileURL(join(root, 'frontend', 'src', 'lib', 'exercises-data.js')))
const known = new Set(EXDB.map(exercise => exercise.id))

for (const lang of ['zh', 'zh-TW']) {
  const sourcePath = join(root, 'scripts', 'exercise-name-sources', `${lang}.json`)
  const outputPath = join(root, 'frontend', 'src', 'exercise-names', `${lang}.js`)
  const source = JSON.parse(readFileSync(sourcePath, 'utf8'))
  for (const [id, name] of Object.entries(source)) {
    if (!known.has(id)) throw new Error(`Unknown exercise ID: ${id}`)
    if (typeof name !== 'string' || !name.trim() || !/\p{Script=Han}/u.test(name)) {
      throw new Error(`${lang} ${id}: name must be a non-empty Chinese translation`)
    }
  }
  if (Object.keys(source).length !== EXDB.length) {
    throw new Error(`Incomplete ${lang} exercise names: ${Object.keys(source).length}/${EXDB.length}`)
  }
  const ordered = {}
  for (const exercise of EXDB) ordered[exercise.id] = source[exercise.id].trim()
  mkdirSync(dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, `// generated by scripts/build-zh-exercise-names.mjs — edit scripts/exercise-name-sources/${lang}.json\nexport default ` + JSON.stringify(ordered) + '\n')
  console.log(`Generated ${EXDB.length}/${EXDB.length} ${lang} exercise names.`)
}
