#!/usr/bin/env node
// The Google Play asset packs of the exercise animations (Play Asset Delivery, on demand), put
// into the Android project on the release machine right before the Play bundle is built, and
// taken out again after. They are never committed (frontend/android/.gitignore) and never built in
// CI: the animations above 180 px may only ever reach people inside the store app (Gym visual
// licence, Part B), and Google Play delivers these packs itself.
//
//   node scripts/android/make-asset-packs.mjs [--px 360,480,720,1080] [--builtin 240]
//        [--src-root /mnt/backup-hdd/opengym-media/quality] [--src 480=/other/480] [--limit N]
//   node scripts/android/make-asset-packs.mjs --clean
//   ... --dry-run   only says what it would make
//
// Per quality and figure the same files as the iPhone's packs (scripts/media/make-pack-manifests.mjs,
// packDrawingId in frontend/src/lib/anim-quality.js): `anim-<px>-<figure>`, inside it
// `<packId>/<drawing>.webp`. Only qualities sharper than the built-in files (--builtin, the
// APK's 240) and whose folder exists are made. A Play pack name must be a Gradle module name, so
// anim-480-male is the module anim_480_male; a pack over Play's 1.5 GB per-pack limit is split
// into anim_480_male_p1, _p2, ... (the app fetches them together).
//
// Writes:
//   frontend/android/anim_<px>_<figure>[_pN]/   one asset-pack module each (files hard-linked)
//   frontend/android/asset-packs.settings.gradle  include ':anim_...' for settings.gradle
//   frontend/android/asset-packs.app.gradle       android.assetPacks for app/build.gradle
//   frontend/android/app/src/play/assets/anim-packs.json   what the app's plugin offers:
//     { "anim-480-male": { "parts": ["anim_480_male"], "files": 5619, "bytes": 786000000 }, ... }
// Without these files (any checkout, CI) the Play build simply has no packs and shows its
// built-in animations.
//
// --limit N: only the first N drawings of each pack (plus the one the app probes), for a quick
// emulator test with bundletool --local-testing. Never for a release.
//
// LICENCE: names and sizes only. This never opens, decodes or looks at a media file.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { EXDB } from '../../frontend/src/lib/exercises-data.js'
import { PACK_QUALITIES, FIGURES, packId, packDrawingId } from '../../frontend/src/lib/anim-quality.js'
import { drawingsFor } from '../media/make-pack-manifests.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
export const ANDROID = path.join(ROOT, 'frontend/android')
// Play's limit is 1.5 GB per asset pack; a margin below it for the pack's own overhead.
export const PART_MAX_BYTES = 1400 * 1024 * 1024
const PROBE_EX = '0001'   // lib/anim-packs.js probeFor: the drawing the app checks a pack by

/** anim-480-male → anim_480_male (a Gradle module and Play pack name). */
export const moduleName = (id, part = 0) => id.replace(/-/g, '_') + (part ? `_p${part}` : '')

/** Splits [{ id, bytes }] into parts of at most `max` bytes each, in order. */
export function splitParts(files, max = PART_MAX_BYTES) {
  const parts = [[]]
  let size = 0
  for (const f of files) {
    if (size + f.bytes > max && parts.at(-1).length) { parts.push([]); size = 0 }
    parts.at(-1).push(f)
    size += f.bytes
  }
  return parts
}

/**
 * The packs to make: [{ id, px, figure, parts: [{ module, files: [{ id, src, bytes }] }], bytes }].
 * `sizeOf(path)` is the file size or null when it is missing (a missing file is an error: a
 * pack must hold every drawing the app may ask it for).
 */
export function planPacks({ qualities, srcFor, sizeOf, catalogue = EXDB, limit = 0, max = PART_MAX_BYTES }) {
  const plan = []
  for (const px of qualities) {
    for (const figure of FIGURES) {
      let ids = drawingsFor(catalogue, figure)
      if (limit > 0) {
        const probe = packDrawingId(catalogue.find(e => e.id === PROBE_EX), figure)
        ids = [...new Set([probe, ...ids.slice(0, limit)])].filter(Boolean)
      }
      const files = ids.map(id => {
        const src = path.join(srcFor(px), `${id}.webp`)
        const bytes = sizeOf(src)
        if (bytes == null) throw new Error(`missing ${px} px drawing ${id} (${src})`)
        return { id, src, bytes }
      })
      const id = packId(px, figure)
      const groups = splitParts(files, max)
      plan.push({
        id, px, figure,
        bytes: files.reduce((n, f) => n + f.bytes, 0),
        parts: groups.map((g, i) => ({ module: moduleName(id, groups.length > 1 ? i + 1 : 0), files: g })),
      })
    }
  }
  return plan
}

export const moduleGradle = name => `// Generated by scripts/android/make-asset-packs.mjs: not committed.
apply plugin: 'com.android.asset-pack'

assetPack {
    packName = "${name}"
    dynamicDelivery {
        deliveryType = "on-demand"
    }
}
`

/** What the app's plugin reads (assets/anim-packs.json). */
export const packIndex = plan => Object.fromEntries(plan.map(p => [p.id, {
  parts: p.parts.map(x => x.module),
  files: p.parts.reduce((n, x) => n + x.files.length, 0),
  bytes: p.bytes,
}]))

const GENERATED = ['asset-packs.settings.gradle', 'asset-packs.app.gradle', 'app/src/play/assets/anim-packs.json']

export function clean(android = ANDROID) {
  for (const d of fs.readdirSync(android)) {
    if (/^anim_\d+_(male|female)(_p\d+)?$/.test(d)) fs.rmSync(path.join(android, d), { recursive: true, force: true })
  }
  for (const f of GENERATED) fs.rmSync(path.join(android, f), { force: true })
}

function place(src, dest) {
  try { fs.linkSync(src, dest) } catch { fs.copyFileSync(src, dest) }
}

export function write(plan, android = ANDROID) {
  clean(android)
  for (const p of plan) {
    for (const part of p.parts) {
      const dir = path.join(android, part.module)
      const assets = path.join(dir, 'src/main/assets', p.id)
      fs.mkdirSync(assets, { recursive: true })
      fs.writeFileSync(path.join(dir, 'build.gradle'), moduleGradle(part.module))
      for (const f of part.files) place(f.src, path.join(assets, `${f.id}.webp`))
    }
  }
  const modules = plan.flatMap(p => p.parts.map(x => x.module))
  const head = '// Generated by scripts/android/make-asset-packs.mjs: not committed.\n'
  fs.writeFileSync(path.join(android, 'asset-packs.settings.gradle'), head + modules.map(m => `include ':${m}'`).join('\n') + '\n')
  fs.writeFileSync(path.join(android, 'asset-packs.app.gradle'), head + `android {\n    assetPacks = [${modules.map(m => `":${m}"`).join(', ')}]\n}\n`)
  const assets = path.join(android, 'app/src/play/assets')
  fs.mkdirSync(assets, { recursive: true })
  fs.writeFileSync(path.join(assets, 'anim-packs.json'), JSON.stringify(packIndex(plan), null, 2) + '\n')
}

function main(argv) {
  const opt = name => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : null }
  if (argv.includes('--clean')) { clean(); console.log('asset packs removed from the Android project'); return }
  const builtin = Number(opt('--builtin') || 240)
  const srcRoot = opt('--src-root') || '/mnt/backup-hdd/opengym-media/quality'
  const overrides = Object.fromEntries(argv.flatMap((a, i) => (a === '--src' ? [argv[i + 1].split('=')] : [])).map(([px, dir]) => [Number(px), dir]))
  const srcFor = px => overrides[px] || path.join(srcRoot, String(px))
  const asked = opt('--px') ? opt('--px').split(',').map(Number) : PACK_QUALITIES
  if (asked.some(px => !PACK_QUALITIES.includes(px))) { console.error(`--px: only ${PACK_QUALITIES.join(', ')}`); process.exit(2) }
  const qualities = asked.filter(px => px > builtin && fs.existsSync(srcFor(px)))
  const skipped = asked.filter(px => !qualities.includes(px))
  if (skipped.length) console.log(`skipped (not sharper than ${builtin} px, or no folder): ${skipped.join(', ')}`)
  if (!qualities.length) { console.error('no quality to make a pack of'); process.exit(1) }
  const limit = Number(opt('--limit') || 0)
  const sizeOf = f => { try { return fs.statSync(f).size } catch { return null } }
  const plan = planPacks({ qualities, srcFor, sizeOf, limit })
  if (!argv.includes('--dry-run')) write(plan)
  for (const p of plan) {
    console.log(`${p.id}: ${p.parts.reduce((n, x) => n + x.files.length, 0)} files, ${(p.bytes / 1024 / 1024).toFixed(1)} MB, ${p.parts.map(x => x.module).join(' + ')}`)
  }
  if (limit) console.log(`--limit ${limit}: a TEST set, not for a release`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main(process.argv.slice(2))
