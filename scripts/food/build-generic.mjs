#!/usr/bin/env node
// Builds frontend/src/lib/food-generic-data.js: generic foods per 100 g for the food diary search,
// from USDA FoodData Central "SR Legacy" (public domain). Needs network and the system `unzip`.
//   node scripts/food/build-generic.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const URL_ZIP = 'https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_sr_legacy_food_csv_2018-04.zip';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '../../frontend/src/lib/food-generic-data.js');
// Baby foods and infant formula are not what people search for in a diary.
const SKIP_CATEGORIES = new Set(['Baby Foods']);
// nutrient.csv ids: energy kcal, energy kJ, protein, fat, carbs, fiber, sugars, sodium mg
const N = { kcal: 1008, kj: 1062, p: 1003, f: 1004, c: 1005, fib: 1079, sug: 2000, na: 1093 };

// RFC 4180: quoted fields may hold commas, newlines and doubled quotes.
export function parseCsv(text) {
  const rows = [];
  let row = [], f = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"') { if (text[i + 1] === '"') { f += '"'; i++; } else q = false; }
      else f += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(f); f = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(f); f = '';
      rows.push(row); row = [];
    } else f += ch;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  return rows;
}

const table = (path) => {
  const [head, ...rest] = parseCsv(readFileSync(path, 'utf8')).filter((r) => r.length > 1);
  return rest.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
};

const r1 = (x) => Math.round(x * 10) / 10;

async function main() {
  const dir = mkdtempSync(join(tmpdir(), 'sr-legacy-'));
  const zip = join(dir, 'sr.zip');
  const res = await fetch(URL_ZIP);
  if (!res.ok) throw new Error(`download failed: ${res.status}`);
  writeFileSync(zip, Buffer.from(await res.arrayBuffer()));
  execFileSync('unzip', ['-q', '-o', zip, '-d', dir]);
  const sub = join(dir, 'FoodData_Central_sr_legacy_food_csv_2018-04');

  const cats = new Map(table(join(sub, 'food_category.csv')).map((c) => [c.id, c.description]));
  const foods = new Map();
  for (const f of table(join(sub, 'food.csv'))) {
    if (!SKIP_CATEGORIES.has(cats.get(f.food_category_id))) foods.set(f.fdc_id, { name: f.description, v: {} });
  }
  const wanted = new Set(Object.values(N).map(String));
  for (const n of table(join(sub, 'food_nutrient.csv'))) {
    const food = foods.get(n.fdc_id);
    if (food && wanted.has(n.nutrient_id) && n.amount !== '') food.v[n.nutrient_id] = Number(n.amount);
  }

  const rows = [];
  for (const { name, v } of foods.values()) {
    const kcal = v[N.kcal] ?? (v[N.kj] != null ? v[N.kj] / 4.184 : null);
    if (kcal == null || !Number.isFinite(kcal)) continue;
    const g = (id) => r1(v[id] || 0);
    rows.push([name, Math.round(kcal), g(N.p), g(N.c), g(N.f), g(N.fib), g(N.sug),
      Math.round(((v[N.na] || 0) * 2.5) / 10) / 100]);
  }
  rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

  const body = rows.map((r) => JSON.stringify(r)).join(',\n');
  writeFileSync(OUT, `// Generated by scripts/food/build-generic.mjs from USDA FoodData Central SR Legacy (public domain). Do not edit.\nexport default [\n${body}\n]\n`);
  console.log(`${rows.length} rows, ${(statSync(OUT).size / 1024).toFixed(0)} KB -> ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
