#!/usr/bin/env node
// Regenerates frontend/src/exercise-names/de.js from the curated source in
// scripts/exercise-name-sources/de.json.
//
//   node scripts/build-de-exercise-names.mjs
//
// German ships as a stage: the 999 catalogue entries that use equipment, and not the 325
// body-weight ones, whose names keep their English title through the per-exercise fallback in
// exerciseNameFor. The coverage gate below is therefore not "how many" but "exactly which" —
// a pack that quietly lost a dumbbell entry, or gained a body-weight one, is a different
// promise from the one the README makes.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { AWAITING_REVIEW, BODY_WEIGHT, stagedExercises } from './de-name-rules.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = join(root, 'scripts', 'exercise-name-sources', 'de.json')
const outputPath = join(root, 'frontend', 'src', 'exercise-names', 'de.js')
const exercisesPath = join(root, 'frontend', 'src', 'lib', 'exercises-data.js')

const source = JSON.parse(readFileSync(sourcePath, 'utf8'))
const { EXDB } = await import(pathToFileURL(exercisesPath))
const staged = stagedExercises(EXDB)
const expected = new Set(staged.map(exercise => exercise.id))
const known = new Map(EXDB.map(exercise => [exercise.id, exercise]))

for (const id of Object.keys(source)) {
  const exercise = known.get(id)
  if (!exercise) throw new Error(`Unknown exercise ID: ${id}`)
  if (typeof source[id] !== 'string' || !source[id].trim()) throw new Error(`${id}: name must be a non-empty string`)
  if (!expected.has(id)) throw new Error(`${id} (${exercise.n}) is ${exercise.eq || 'equipment-free'} — outside the staged equipment set`)
}
const missing = staged.filter(exercise => !source[exercise.id])
if (missing.length) {
  const sample = missing.slice(0, 5).map(exercise => `${exercise.id} (${exercise.n})`).join(', ')
  throw new Error(`Incomplete de exercise names: ${Object.keys(source).length}/${staged.length} — missing ${missing.length}, e.g. ${sample}`)
}

const ordered = {}
for (const exercise of staged) ordered[exercise.id] = source[exercise.id].trim()
mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, '// generated by scripts/build-de-exercise-names.mjs — edit scripts/exercise-name-sources/de.json\nexport default ' + JSON.stringify(ordered) + '\n')
const bodyWeight = EXDB.filter(exercise => !exercise.eq || exercise.eq === BODY_WEIGHT).length
console.log(`Generated ${staged.length}/${EXDB.length} de exercise names (reviewed equipment exercises; ${bodyWeight} body-weight and ${AWAITING_REVIEW.size} awaiting-review names keep their English title).`)
